const STRINGS: Record<Lang, Partial<Record<StringKey, string>>> = { en, ru, uz };

export type { StringKey };

export function isLang(v: string | null): v is Lang {
  return v === "en" || v === "ru" || v === "uz";
}

export function loadLang(): Lang {
  try {
    const stored = localStorage.getItem("onflip.lang");
    return isLang(stored) ? stored : "en";
  } catch {
    return "en";
  }
}

export function saveLang(lang: Lang): void {
  try {
    localStorage.setItem("onflip.lang", lang);
  } catch {
    /* cosmetic */
  }
}

export const LangContext = createContext<Lang>("en");

export function translate(
  lang: Lang,
  key: StringKey,
  params?: Record<string, string | number>
): string {
  let text = STRINGS[lang][key] ?? en[key] ?? key;
  if (params) {
    for (const [name, value] of Object.entries(params)) {
      text = text.replace(`{${name}}`, String(value));
    }
  }
  return text;
}

/** Translator bound to the active language; missing keys fall back to English. */
export function useT(): (key: StringKey, params?: Record<string, string | number>) => string {
  const lang = useContext(LangContext);
  return (key, params) => translate(lang, key, params);
}
